// IQ3_S and IQ2_S linear for 1-8 activation rows. llama.cpp's MMVQ decodes each weight block (grid lookups, signs) once per
// activation row, so a speculative verification of 5 rows costs 5 decodes; here each 32-value sub-block is decoded once and its
// signed values are multiplied with every row (DP4A, exact integer sums). A warp stages four super-blocks of each of its output
// features with coalesced 16-byte loads, whatever the alignment of the row (110- and 82-byte blocks), and each lane owns one
// sub-block. Per row and sub-block the product is (d_w * d_x) * integer sum, accumulated per lane and reduced in a fixed order:
// an output row is computed the same way whatever the number of rows.
// Activations: d = amax / 127 per 32 values kept in FP32 (MMVQ rounds it to FP16), q = round(x / d). IQ2_S scales its two halves
// by (ls + 0.5) / 4 exactly, where MMVQ truncates two integer divisions.
// Header-free CUDA: NVRTC ships with PyTorch. Defines from the host: QTYPE (3: IQ3_S, 2: IQ2_S), NCOLS (rows), R (output features
// per warp), WARPS, XTYPE, DTYPE, SILU; the matrix size is a launch argument: one compilation per configuration, whatever the shapes.
using u8 = unsigned char;
using u16 = unsigned short;
using u32 = unsigned int;
using u64 = unsigned long long;

__device__ float half_float(u16 value) {
    float result;
    asm("cvt.f32.f16 %0, %1;" : "=f"(result) : "h"(value));
    return result;
}
__device__ u16 float_half(float value) {
    u16 result;
    asm("cvt.rn.f16.f32 %0, %1;" : "=h"(result) : "f"(value));
    return result;
}
__device__ float bf16_float(u16 value) {
    union { u32 bits; float value; } data;
    data.bits = u32(value) << 16;
    return data.value;
}
__device__ u16 float_bf16(float value) {
    union { u32 bits; float value; } data;
    data.value = value;
    if ((data.bits & 0x7fffffffU) > 0x7f800000U) return u16((data.bits >> 16) | 64);
    return u16((data.bits + 0x7fffU + ((data.bits >> 16) & 1)) >> 16);
}
template<int TYPE> __device__ float read_value(const void* data, long long index) {
    if constexpr (TYPE == 0) return half_float(((const u16*)data)[index]);
    if constexpr (TYPE == 1) return bf16_float(((const u16*)data)[index]);
    return ((const float*)data)[index];
}
template<int TYPE> __device__ float round_value(float value) {  // the value as its tensor type stores it
    if constexpr (TYPE == 0) return half_float(float_half(value));
    if constexpr (TYPE == 1) return bf16_float(float_bf16(value));
    return value;
}
template<int TYPE> __device__ void write_value(void* data, long long index, float value) {
    if constexpr (TYPE == 0) ((u16*)data)[index] = float_half(value);
    else if constexpr (TYPE == 1) ((u16*)data)[index] = float_bf16(value);
    else ((float*)data)[index] = value;
}

// Q8 activations per 32 values: d = amax / 127, q = round(x / d). SILU: x holds the gate then the value of a SwiGLU (2 K per row);
// silu(gate) and its product with the value are rounded to the activation type, as the separate operations store them.
extern "C" __global__ void __launch_bounds__(256) iq_quantize(const void* x, long long x_stride, signed char* q, float* d, int K) {
    const int block = blockIdx.x * 8 + (threadIdx.x >> 5), lane = threadIdx.x & 31, row = blockIdx.y;
    if (block >= K / 32) return;
    const int col = block * 32 + lane;
#if SILU
    const float gate = read_value<XTYPE>(x, row * x_stride + col), value = read_value<XTYPE>(x, row * x_stride + K + col);
    const float xi = round_value<XTYPE>(round_value<XTYPE>(gate / (1.0f + expf(-gate))) * value);
#else
    const float xi = read_value<XTYPE>(x, row * x_stride + col);
#endif
    float amax = fabsf(xi);
#pragma unroll
    for (int mask = 16; mask > 0; mask >>= 1) amax = fmaxf(amax, __shfl_xor_sync(0xffffffffu, amax, mask));
    const float scale = amax / 127.0f;
#if MMA  // the tensor-core kernel's order: the eight values of quad thread t for the eight sub-blocks of a super-block side by side (64 bytes, four loads)
    const int position = (col & ~255) + ((col >> 3) & 3) * 64 + ((col >> 5) & 7) * 8 + (col & 7);
#else
    const int position = col;
#endif
    q[(long long)row * K + position] = amax == 0.0f ? 0 : (signed char)roundf(xi / scale);
    if (lane == 0) d[(long long)row * (K / 32) + block] = scale;
}

